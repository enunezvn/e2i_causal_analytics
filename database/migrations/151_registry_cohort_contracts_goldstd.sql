-- PROVABLE (measured 2026-09-23, read-only):
--   * 9 patient rows <cohort>_<brand>_goldstd_lr_v1 were trained by FeatureBuilder on
--     patient_journeys WHERE brand=<brand> AND is_synthetic=true, label
--     _PATIENT_LABELS[cohort] (treatment_initiated / persistent_180d /
