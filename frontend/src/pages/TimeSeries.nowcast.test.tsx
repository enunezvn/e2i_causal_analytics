/**
 * TimeSeries — claims-lag provisional treatment + nowcast overlay (backlog #45, PR-C)
 * ===================================================================================
 *
 * Page-level spec for the Rx-volume nowcast surface:
 *  - the nowcast fetch is gated to the Rx-volume family (off-family KPIs
 *    never fire the request — the endpoint would 422)                     (e)
 *  - with a populated arrival plane the chart splits into a solid mature
 *    segment + dashed provisional tail with hollow markers               (a)
 *  - the "Show Nowcast" toggle defaults OFF, renders the overlay + CI
 *    band when enabled, and persists the choice to localStorage          (c)
 *  - the LIVE degraded state (insufficient_maturity=true,
 *    reason='arrival_plane_not_populated') renders the mature chart
 *    untouched with an honest, disabled affordance — no overlay, no
 *    fabricated values, no error                                          (d)
 *
 * ResponsiveContainer is mocked with fixed dimensions (jsdom's
 * ResizeObserver stub never sizes it — probed before writing this spec).
 * KPICard sparklines also render recharts under this mock, so every chart
 * assertion is SCOPED to the "KPI History" card.
 */

