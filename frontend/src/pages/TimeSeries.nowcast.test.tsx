/** Chart assertions are scoped to the KPI History card (KPICard sparklines
 *  also render recharts under the sized ResponsiveContainer mock). */
function chartCard(): HTMLElement {
  const card = screen.getByText('KPI History').closest('div[class*="rounded"]');
  expect(card).not.toBeNull();
  return card as HTMLElement;
}

function lineCurveCount(scope: HTMLElement): number {
  return scope.querySelectorAll('.recharts-line-curve').length;
}

/** The provisional tail renders as its own Line layer with this class hook
 *  (jsdom freezes recharts' draw-in animation at frame 0, overwriting
 *  stroke-dasharray on every curve — the class is the stable contract). */
function provisionalLayerCount(scope: HTMLElement): number {
  return scope.querySelectorAll('.metric-trend-provisional').length;
}

describe('TimeSeries nowcast (backlog #45 PR-C)', () => {
  // ===========================================================================
  // (e) off-family gating
  // ===========================================================================

  it('gates the nowcast fetch off for off-family KPIs and shows no affordance', () => {
    render(<TimeSeries />, { wrapper: createWrapper() });

    expect(mockUseKPIHistoryNowcast).toHaveBeenCalled();
    const offFamilyCalls = mockUseKPIHistoryNowcast.mock.calls.filter(
      (c: unknown[]) => c[0] === 'WS3-BI-010'
    );
    expect(offFamilyCalls.length).toBeGreaterThan(0);
    for (const call of offFamilyCalls) {
      expect((call[2] as { enabled?: boolean } | undefined)?.enabled).toBe(false);
    }
    expect(screen.queryByRole('button', { name: /show nowcast/i })).not.toBeInTheDocument();
  });

  it('enables the fetch for an Rx-volume KPI', async () => {
    const user = userEvent.setup();
    mockNowcast(NOWCAST_OK);
    render(<TimeSeries />, { wrapper: createWrapper() });
    await selectTRx(user);

    await waitFor(() => {
      const calls = mockUseKPIHistoryNowcast.mock.calls.filter(
        (c: unknown[]) => c[0] === 'WS3-BI-005'
      );
      expect(calls.length).toBeGreaterThan(0);
      expect(
        (calls[calls.length - 1][2] as { enabled?: boolean } | undefined)?.enabled
      ).toBe(true);
    });
  });

  it('with a region selected the fetch is gated off and the toggle says why (#1536)', async () => {
    const user = userEvent.setup();
    mockNowcast(NOWCAST_OK);
    // TRx grows region scopes in coverage — the region selector appears.
    mockUseKPIHistoryCoverage.mockReturnValue(
      queryResult({
        coverage: [
          coverage[0],
          {
            ...coverage[1],
            scopes: [
              {
                brand: '',
                region: '',
                points: 7,
                first_date: '2026-01-01',
                last_date: '2026-07-01',
              },
              {
                brand: '',
                region: 'northeast',
                points: 7,
                first_date: '2026-01-01',
                last_date: '2026-07-01',
              },
            ],
          },
        ],
        total: 2,
      })
    );
    render(<TimeSeries />, { wrapper: createWrapper() });
    await selectTRx(user);

    await user.click(await screen.findByRole('combobox', { name: /^region$/i }));
    await user.click(await screen.findByRole('option', { name: 'northeast' }));

    // The nowcast endpoint has no region dimension: the fetch gates off...
    await waitFor(() => {
      const calls = mockUseKPIHistoryNowcast.mock.calls.filter(
        (c: unknown[]) => c[0] === 'WS3-BI-005'
      );
      expect(
        (calls[calls.length - 1][2] as { enabled?: boolean } | undefined)?.enabled
      ).toBe(false);
    });
    // ...and the affordance stays visible but disabled with the reason —
    // never silently absent, never a mislabeled portfolio overlay.
    expect(screen.getByRole('button', { name: /show nowcast/i })).toBeDisabled();
    expect(screen.getByText(/no region dimension/i)).toBeInTheDocument();
  });

  // ===========================================================================
  // (a) provisional tail — default view
  // ===========================================================================

  it('renders the provisional tail dashed with hollow markers, overlay OFF by default', async () => {
    const user = userEvent.setup();
    mockNowcast(NOWCAST_OK);
    render(<TimeSeries />, { wrapper: createWrapper() });
    await selectTRx(user);

    const toggle = await screen.findByRole('button', { name: /show nowcast/i });
    expect(toggle).toHaveAttribute('aria-pressed', 'false');

    const card = chartCard();
    // Solid mature segment + dashed provisional tail.
    expect(lineCurveCount(card)).toBe(2);
    expect(provisionalLayerCount(card)).toBe(1);
    // Hollow markers on exactly the 2 provisional months.
    const hollowCount = [...card.querySelectorAll('.recharts-line-dots circle')].filter(
      (c) => c.getAttribute('fill') === 'var(--color-background)'
    ).length;
    expect(hollowCount).toBe(2);
    // Default view carries NO nowcast overlay — honest mature series only.
    expect(card.querySelector('.recharts-area')).not.toBeInTheDocument();

    // Footnote defines "provisional" and carries the claims frontier date.
    const footnote = screen.getByTestId('nowcast-footnote');
    expect(footnote.textContent).toMatch(/provisional/i);
    expect(footnote.textContent).toMatch(/Jul 21/);
    // The excluded frontier month is disclosed, not silently dropped.
    expect(footnote.textContent).toMatch(/frontier month/i);
  });

  // ===========================================================================
  // (c) opt-in overlay + persistence
  // ===========================================================================

  it('toggle ON renders overlay + CI band and persists; OFF hides and persists', async () => {
    const user = userEvent.setup();
    mockNowcast(NOWCAST_OK);
    render(<TimeSeries />, { wrapper: createWrapper() });
    await selectTRx(user);

    const toggle = await screen.findByRole('button', { name: /show nowcast/i });
    await user.click(toggle);

    expect(toggle).toHaveAttribute('aria-pressed', 'true');
    const card = chartCard();
    expect(card.querySelector('.recharts-area')).toBeInTheDocument();
    expect(lineCurveCount(card)).toBe(3);
    expect(localStorage.getItem(SHOW_NOWCAST_STORAGE_KEY)).toBe('true');

    await user.click(toggle);
    expect(toggle).toHaveAttribute('aria-pressed', 'false');
    expect(chartCard().querySelector('.recharts-area')).not.toBeInTheDocument();
    expect(localStorage.getItem(SHOW_NOWCAST_STORAGE_KEY)).toBe('false');
  });

  it('initializes the overlay from the persisted preference', async () => {
    const user = userEvent.setup();
    localStorage.setItem(SHOW_NOWCAST_STORAGE_KEY, 'true');
    mockNowcast(NOWCAST_OK);
    render(<TimeSeries />, { wrapper: createWrapper() });
    await selectTRx(user);

    const toggle = await screen.findByRole('button', { name: /show nowcast/i });
    expect(toggle).toHaveAttribute('aria-pressed', 'true');
    expect(chartCard().querySelector('.recharts-area')).toBeInTheDocument();
  });

  // ===========================================================================
  // (d) LIVE degraded state — arrival plane not populated
  // ===========================================================================

  it('degrades cleanly when the arrival plane is not populated', async () => {
    const user = userEvent.setup();
    // beforeEach default IS the degraded live state.
    render(<TimeSeries />, { wrapper: createWrapper() });
    await selectTRx(user);

    // The mature chart renders untouched: one solid line, no dashes, no band.
    const card = chartCard();
    await waitFor(() => expect(lineCurveCount(card)).toBe(1));
    expect(provisionalLayerCount(card)).toBe(0);
    expect(card.querySelector('.recharts-area')).not.toBeInTheDocument();

    // Honest affordance: the toggle is disabled with a truthful explanation —
    // never absent-but-broken, never a fabricated overlay.
    const toggle = screen.getByRole('button', { name: /show nowcast/i });
    expect(toggle).toBeDisabled();
    expect(screen.getByText(/nowcast unavailable/i)).toBeInTheDocument();
    expect(
      screen.getByText(/claims-arrival dates are not populated/i)
    ).toBeInTheDocument();

    // No error surface: degradation is an expected state, not a failure.
    expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  });

  // ===========================================================================
  // Export honesty
  // ===========================================================================

  it('export carries the nowcast block only while the provisional view is active', async () => {
    const user = userEvent.setup();
    mockNowcast(NOWCAST_OK);
    const clickSpy = vi
      .spyOn(HTMLAnchorElement.prototype, 'click')
      .mockImplementation(() => {});
    const createObjectURL = global.URL.createObjectURL as ReturnType<typeof vi.fn>;

    render(<TimeSeries />, { wrapper: createWrapper() });

    // Off-family default KPI: no nowcast key in the export payload.
    await user.click(screen.getByRole('button', { name: /export/i }));
    const readBlob = (blob: Blob) =>
      new Promise<string>((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = () => resolve(reader.result as string);
        reader.onerror = () => reject(reader.error);
        reader.readAsText(blob);
      });
    const first = JSON.parse(await readBlob(createObjectURL.mock.calls[0]?.[0] as Blob));
    expect(first).not.toHaveProperty('nowcast');

    // TRx with a populated plane: the provisional/nowcast points ride along.
    await selectTRx(user);
    await screen.findByRole('button', { name: /show nowcast/i });
    await user.click(screen.getByRole('button', { name: /export/i }));
    const second = JSON.parse(await readBlob(createObjectURL.mock.calls[1]?.[0] as Blob));
    expect(second.kpiId).toBe('WS3-BI-005');
    expect(second.nowcast).toBeDefined();
    expect(second.nowcast.data_through).toBe('2026-07-21');
    expect(Array.isArray(second.nowcast.points)).toBe(true);
    expect(second.nowcast.points.some((p: { provisional: boolean }) => p.provisional)).toBe(
      true
    );
    clickSpy.mockRestore();
  });
});
