--     in MLDataLoader.ML_TABLES, and the scope_definer rewrites any target containing
--     "adopt" to `will_adopt` (problem_classifier._infer_target_variable), so a table
--     retrain would fail the loader's target guard. Known pre-existing limit.
--   * both columns for the 2 archived csu_treatment_initiation_lr_* rows: trained on
--     an in-process generated dataset (src/mlops/prediction_synthesizer_deploy.py),
--     not on any table.
--   * cohort_feature_manifest_source everywhere: no goldstd path resolves a Layer-5
--     manifest.
